import {test,expect} from "@playwright/test";
import {pathToFileURL} from "node:url";
import {resolve} from "node:path";
import {mkdirSync} from "node:fs";
test("adopted subobjective labels remain readable on offline landscape mission selection",async({page,context},info)=>{
 await context.setOffline(true);
 await page.goto(pathToFileURL(resolve("dist/robot-tactics-offline/index.html")).href);
 await page.getByRole("button",{name:"ミッション選択",exact:true}).click();
 await page.getByRole("button",{name:/^M01 /}).click();
 await expect(page.getByText("副目標：出撃時の自機3機の武器①②に斬撃・連射・狙撃を含めてクリア",{exact:true})).toBeVisible();
 await expect(page.getByText("副目標：防衛施設の残HP40%以上でクリア",{exact:true})).toHaveCount(2);
 await page.getByRole("button",{name:/^M05 /}).click();
 await expect(page.getByText("副目標：輸送車の残HP50%以上でクリア",{exact:true})).toBeVisible();
 const hard=page.getByText(/^副目標：R4以降、輸送車の周囲8マス/);await expect(hard).toHaveCount(2);await hard.last().scrollIntoViewIfNeeded();await expect(hard.last()).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth&&document.documentElement.scrollHeight<=innerHeight)).toBe(true);
 mkdirSync("test-results/robot-vfx-review",{recursive:true});await page.screenshot({path:`test-results/robot-vfx-review/${info.project.name}-subobjectives.png`});
 await page.getByRole("button",{name:/^M08 /}).click();
 await expect(page.getByText(/^副目標：出撃時の自機3機/)).toBeVisible();
 await page.getByRole("button",{name:/^M10 /}).click();
 await expect(page.getByText(/^副目標：出撃時の自機3機に機動力・防御型フレームを/)).toBeVisible();
 await expect(page.getByText(/^副目標：最初に突破ラインに到達した自機が/)).toHaveCount(2);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth&&document.documentElement.scrollHeight<=innerHeight)).toBe(true);
});
